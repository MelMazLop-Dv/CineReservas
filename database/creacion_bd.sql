
-- PROYECTO: CineReservas
-- Script de creación de tablas
-- Base de datos: cine_reservas

CREATE TABLE IF NOT EXISTS funciones (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         pelicula VARCHAR(255) NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    sala VARCHAR(255) NOT NULL,
    capacidad INTEGER NOT NULL,
    asientos_disponibles INTEGER NOT NULL,
    precio_entrada NUMERIC(12,2) NOT NULL,

    CONSTRAINT chk_capacidad
    CHECK (capacidad > 0),

    CONSTRAINT chk_asientos
    CHECK (
              asientos_disponibles >= 0
              AND asientos_disponibles <= capacidad
          ),

    CONSTRAINT chk_precio
    CHECK (precio_entrada >= 0)
    );

CREATE TABLE IF NOT EXISTS reservas (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        nombre_cliente VARCHAR(255) NOT NULL,
    cantidad_entradas INTEGER NOT NULL,
    precio_total NUMERIC(12,2) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    funcion_id BIGINT NOT NULL,

    CONSTRAINT fk_reserva_funcion
    FOREIGN KEY (funcion_id)
    REFERENCES funciones(id),

    CONSTRAINT chk_cantidad
    CHECK (cantidad_entradas > 0),

    CONSTRAINT chk_total
    CHECK (precio_total >= 0),

    CONSTRAINT chk_estado
    CHECK (estado IN ('CONFIRMADA', 'CANCELADA'))
    );
